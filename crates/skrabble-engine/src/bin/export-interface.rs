use skrabble_engine::{model::*, rules};
use ts_rs::TS;

fn main() {
    println!("// Generated by the Rust engine. Run bun run build:engine; do not edit.\n");
    let declarations = [
        TileData::decl(),
        BoardCellState::decl(),
        Position::decl(),
        PlacementHistoryEntry::decl(),
        StickerType::decl(),
        Sticker::decl(),
        Mode::decl(),
        EncounterStatus::decl(),
        EncounterConfig::decl(),
        EncounterState::decl(),
        DraftState::decl(),
        GameState::decl(),
        InputPosition::decl(),
        TileTarget::decl(),
        ResetTarget::decl(),
        DrawCount::decl(),
        AllTiles::decl(),
        GameAction::decl(),
        WordDirection::decl(),
        WordInfo::decl(),
        ScoreBreakdown::decl(),
        PlayScore::decl(),
        PlayEvaluation::decl(),
        TileDefinition::decl(),
    ];
    for declaration in declarations {
        println!("export {declaration}\n");
    }
    for (name, definition) in [
        ("BoardState", Board::inline()),
        ("RackState", Rack::inline()),
        ("StickerState", Stickers::inline()),
    ] {
        println!("export type {name} = {definition};\n");
    }
    let metadata = serde_json::json!({
        "boardSize": BOARD_SIZE,
        "rackSize": RACK_SIZE,
        "draftColumns": DRAFT_COLUMNS,
        "draftSequence": DRAFT_SEQUENCE.iter().map(char::to_string).collect::<Vec<_>>(),
        "encounter": EncounterConfig::default(),
        "tiles": rules::tile_definitions(),
        "blank": rules::tile_definition("*").expect("blank definition"),
    });
    println!(
        "export const ENGINE_META = {} as const;",
        serde_json::to_string_pretty(&metadata).expect("engine metadata")
    );
}
